// Builds styles.css from the shared glass kit, its shared helpers, the plugin's own rules and the shared AI settings styles.
import { readFileSync, writeFileSync } from 'fs';

const kit = readFileSync('styles/apple-kit.css', 'utf8');
const helpers = readFileSync('styles/ap-helpers.css', 'utf8');
const own = readFileSync('styles/plugin.css', 'utf8');
const signature = readFileSync('styles/ap-signature.css', 'utf8');
const ai = readFileSync('src/vendor/rex-ai-kit/rex-ai-kit.css', 'utf8');
writeFileSync('styles.css', `/* Generated by styles/build.mjs. Edit styles/apple-kit.css, styles/ap-helpers.css, styles/plugin.css, styles/ap-signature.css or the kit in src/vendor/rex-ai-kit. */\n\n${kit}\n${helpers}\n${own}\n${signature}\n${ai}`);
